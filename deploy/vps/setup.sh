#!/bin/bash
# OrangeHub VPS setup — Ubuntu/Debian, no Docker / no systemd needed.
# Run as root from a repo clone:
#   git clone https://github.com/VikramMaurya6789/Pornhub.git /opt/orangehub
#   bash /opt/orangehub/deploy/vps/setup.sh
# Re-runnable: skips steps that are already done.
set -e
# This VPS is a container with ~1GB RAM: cap the Node heap so npm/build
# don't get OOM-killed. (Also inherited by the pm2 app at runtime.)
export NODE_OPTIONS="--max-old-space-size=512"
cd "$(dirname "$0")/../.."
REPO_ROOT="$PWD"

rand() { tr -dc 'A-Za-z0-9' < /dev/urandom 2>/dev/null | head -c "$1"; }

echo "=== [1/6] System packages ==="
apt-get update -qq
apt-get install -y -qq curl git postgresql postgresql-contrib cron > /dev/null
# Try to enable 2GB swap (big help on 1GB containers; silently skipped if not permitted)
if ! swapon --show 2>/dev/null | grep -q '^/'; then
  [ -e /swapfile ] || { fallocate -l 2G /swapfile 2>/dev/null && chmod 600 /swapfile && mkswap /swapfile >/dev/null 2>&1; }
  swapon /swapfile 2>/dev/null && echo "2GB swap enabled" || true
fi
echo "OK"

echo "=== [2/6] Node.js 22 ==="
if ! command -v node > /dev/null 2>&1 || ! node -v | grep -q '^v22\.'; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash - > /dev/null 2>&1
  apt-get install -y -qq nodejs > /dev/null
fi
node -v
echo "OK"

echo "=== [3/6] PostgreSQL ==="
service postgresql start 2>/dev/null || pg_ctlcluster "$(ls /etc/postgresql/ | head -1)" main start 2>/dev/null || true
if [ ! -f .env ]; then
  DBPW="$(rand 24)"
  echo "$DBPW" > /tmp/oh_dbpw
  chmod 600 /tmp/oh_dbpw
else
  DBPW="$(grep '^POSTGRES_URL=' .env | sed 's/.*:\/\/[^:]*://; s/@.*//')"
fi
if su postgres -c "psql -tc \"SELECT 1 FROM pg_roles WHERE rolname='orangehub'\"" | grep -q 1; then
  su postgres -c "psql -c \"ALTER USER orangehub WITH PASSWORD '$DBPW'\""
else
  su postgres -c "psql -c \"CREATE USER orangehub WITH PASSWORD '$DBPW'\""
fi
su postgres -c "psql -tc \"SELECT 1 FROM pg_database WHERE datname='orangehub'\"" | grep -q 1 \
  || su postgres -c "psql -c \"CREATE DATABASE orangehub OWNER orangehub\""
rm -f /tmp/oh_dbpw
echo "OK"

echo "=== [4/6] App .env ==="
if [ ! -f .env ]; then
  PUBLIC_IP="$(curl -s --max-time 10 ifconfig.me || echo 127.0.0.1)"
  CRON_SECRET="$(rand 32)"
  cat > .env <<EOF
# Generated by deploy/vps/setup.sh on $(date -u +%F)
POSTGRES_URL=postgresql://orangehub:${DBPW}@localhost:5432/orangehub
CRON_SECRET=${CRON_SECRET}
PORT=3000
NEXT_PUBLIC_SITE_URL=http://${PUBLIC_IP}:3000
# --- Optional: Google login (fill in, then: pm2 restart orangehub) ---
# GOOGLE_CLIENT_ID=
# GOOGLE_CLIENT_SECRET=
# GOOGLE_REDIRECT_URI=http://${PUBLIC_IP}:3000/api/auth/google/callback
# --- Optional: route upstream scraping through a proxy ---
# PROXY_URL=
# FIREBASE_PROJECT_ID=
EOF
  chmod 600 .env
  echo "Created .env (DB password + CRON_SECRET auto-generated)."
else
  echo ".env already exists, keeping it."
  PUBLIC_IP="$(curl -s --max-time 10 ifconfig.me || echo 127.0.0.1)"
fi
echo "OK"

echo "=== [5/6] Install deps + migrate + build (slow on 1GB RAM, do not interrupt) ==="
service postgresql stop 2>/dev/null || true   # free RAM for npm/next build
npm ci --no-audit --no-fund
service postgresql start 2>/dev/null || pg_ctlcluster "$(ls /etc/postgresql/ | head -1)" main start 2>/dev/null || true
npx prisma migrate deploy
npm run build
echo "OK"

echo "=== [6/6] Start with pm2 ==="
npm i -g pm2 --no-audit --no-fund > /dev/null 2>&1 || true
pm2 delete orangehub 2>/dev/null || true
pm2 start node_modules/.bin/next --name orangehub -- start -H 0.0.0.0 -p 3000
pm2 save 2>/dev/null || true
echo "OK"

echo "=== Cron: daily video sync (03:17) ==="
service cron start 2>/dev/null || true
CRON_SECRET="$(grep '^CRON_SECRET=' .env | cut -d= -f2)"
(crontab -l 2>/dev/null | grep -v 'api/cron/sync'; \
 echo "17 3 * * * curl -sf -H \"Authorization: Bearer ${CRON_SECRET}\" http://localhost:3000/api/cron/sync -o /var/log/orangehub-cron.log 2>&1") | crontab -
echo "OK"

echo ""
echo "================================================================"
echo " OrangeHub is starting. Open in your browser:"
echo "   http://${PUBLIC_IP}:3000"
echo " If the page does not load, the provider firewall is blocking"
echo " port 3000 — use a Cloudflare Tunnel instead (see README below)."
echo " NOTE: this machine has no systemd: after a container/VM reboot,"
echo " re-run: cd ${REPO_ROOT} && pm2 resurrect"
echo "================================================================"
